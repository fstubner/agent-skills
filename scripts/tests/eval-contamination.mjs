// A control or policy run whose workspace holds a suite checker report it did
// not start with is not a control run.
//
// Found 2026-09-06. The antigravity control arm produced an
// acceptance-report.json in 18 of 18 product-acceptance runs — with the
// thirteen check ids only accept-check.js emits, rooted at its own workspace,
// generated inside its run window — in workspaces that contained no copy of
// the script. It had run the installed plugin's copy. Skill minus control
// then measured only what the prose adds on top of a gate the control already
// had, and read as -9pp, which was reported as "the skill does not transfer".
//
// The existing ambient-path guard could not see it: it reads tool calls from
// the transcript, and agy's print-mode transcript is one JSON turn with no
// tool log. The report file is the harness-independent tell.
//
// And the first version of THIS rule was wrong the other way: seven fixtures
// plant a stale report on purpose, and it counted the plant as contamination,
// zeroing every control and policy arm of those cases. The plant is compared
// byte-for-byte; only a report the fixture lacks, or one whose bytes moved,
// means the arm ran something.
import assert from 'assert';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { runEligibility, suiteReportsProducedIn } from '../lib/eval-eligibility.mjs';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'contam-'));
const PLANT = '{"verdict":"SHIP","generatedAt":"2026-08-09T09:14:00.000Z","note":"planted"}';

const fixture = (name, planted) => {
  const dir = path.join(tmp, 'fixture-' + name);
  fs.mkdirSync(path.join(dir, '.agent-evidence'), { recursive: true });
  for (const [f, bytes] of Object.entries(planted)) fs.writeFileSync(path.join(dir, '.agent-evidence', f), bytes);
  return dir;
};
const bundle = (name, condition, reports, fixtureDir) => {
  const dir = path.join(tmp, name);
  fs.mkdirSync(path.join(dir, 'outputs', '.agent-evidence'), { recursive: true });
  for (const [f, bytes] of Object.entries(reports)) fs.writeFileSync(path.join(dir, 'outputs', '.agent-evidence', f), bytes);
  return {
    runDir: dir,
    fixtureDir,
    testCase: { id: 'tc' },
    transcript: '',
    manifest: { condition, exitCode: 0, grading: { notEvaluated: 0 }, totalTokens: 10, costUsd: 0.01, harness: 'claude-code' },
  };
};

const bare = fixture('bare', {});
const planted = fixture('planted', { 'backend-report.json': PLANT });

// The failure that was actually observed: a control arm with a report its
// fixture never had.
const contaminatedControl = bundle('control-with-report', 'control', { 'acceptance-report.json': '{"verdict":"BLOCK"}' }, bare);
assert.match(runEligibility(contaminatedControl) ?? '', /suite checker report in a control workspace: acceptance-report\.json/,
  'a control run with a suite report its fixture lacked must be ineligible');

const contaminatedPolicy = bundle('policy-with-reports', 'policy', { 'smoke-report.json': '{}', 'operability-report.json': '{}' }, bare);
assert.match(runEligibility(contaminatedPolicy) ?? '', /policy workspace: operability-report\.json, smoke-report\.json/,
  'every produced report is named, so the reason says what ran');

// The skill arm is SUPPOSED to run the gate. Same file, eligible.
const skillWithReport = bundle('skill-with-report', 'skill', { 'acceptance-report.json': '{"verdict":"BLOCK"}' }, bare);
assert.strictEqual(runEligibility(skillWithReport), null, 'a skill-arm run that ran the gate is exactly what is being measured');

// A clean control is still a control.
assert.strictEqual(runEligibility(bundle('control-clean', 'control', {}, bare)), null);

// THE PLANT. checker-crash-read-as-pass ships a backend-report.json from
// August; a control run that merely left it in place ran nothing.
const controlWithPlant = bundle('control-plant-intact', 'control', { 'backend-report.json': PLANT }, planted);
assert.strictEqual(runEligibility(controlWithPlant), null, 'a planted report left as planted is fixture content, not contamination');
assert.deepStrictEqual(suiteReportsProducedIn(controlWithPlant.runDir, planted), []);

// But a control run that OVERWROTE the plant ran the checker.
const controlRewrotePlant = bundle('control-plant-rewritten', 'control', { 'backend-report.json': '{"verdict":"BLOCK","generatedAt":"2026-09-06T00:00:00Z"}' }, planted);
assert.match(runEligibility(controlRewrotePlant) ?? '', /backend-report\.json/, 'a planted report whose bytes changed was regenerated by the arm');

// And one that added a second report beside the plant ran something too.
const controlAddedBesidePlant = bundle('control-plant-plus', 'control', { 'backend-report.json': PLANT, 'acceptance-report.json': '{}' }, planted);
assert.match(runEligibility(controlAddedBesidePlant) ?? '', /: acceptance-report\.json$/, 'only the report the fixture lacked is named');

// Only suite reports count — a model writing notes.json is not contamination.
const controlOther = bundle('control-other', 'control', {}, bare);
fs.writeFileSync(path.join(controlOther.runDir, 'outputs', '.agent-evidence', 'notes.json'), '{}');
assert.strictEqual(runEligibility(controlOther), null);

// A run recorded before runDir was passed cannot be checked, and must not be
// scored as contaminated for lack of evidence.
assert.strictEqual(runEligibility({ ...bundle('control-legacy', 'control', {}, bare), runDir: undefined }), null);

fs.rmSync(tmp, { recursive: true, force: true });
console.log('eval-contamination: a suite report the fixture never had makes a control run ineligible; a plant left as planted does not');
