#!/usr/bin/env node

import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(fs.readFileSync(path.join(root, 'registry.json'), 'utf8'));
const version = fs.readFileSync(path.join(root, 'VERSION'), 'utf8').trim();
const skillIds = registry.skills.map(({ id }) => id);
const checkOnly = process.argv.includes('--check');
const marker = '.generated-by-agent-skills';
const description = 'Composable, evidence-gated skills for product and software delivery.';

function json(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, json(value));
}

function copyTree(source, destination) {
  fs.cpSync(source, destination, { recursive: true });
}

function vendorCore(skillDestination) {
  const scripts = path.join(skillDestination, 'scripts');
  if (!fs.existsSync(path.join(scripts, 'resolve-core.cjs'))) return;
  const vendor = path.join(scripts, 'vendor');
  copyTree(path.join(root, 'core'), vendor);
  fs.copyFileSync(path.join(root, 'registry.json'), path.join(vendor, 'registry.json'));
}

function assertOwnedOrAbsent(target) {
  if (!fs.existsSync(target)) return;
  if (!fs.existsSync(path.join(target, marker))) {
    throw new Error(`Refusing to replace unowned generated target: ${target}`);
  }
}

function build(destinationRoot) {
  const plugin = path.join(destinationRoot, 'plugins', 'agent-skills');
  const sharedSkills = path.join(destinationRoot, 'skills');

  fs.mkdirSync(plugin, { recursive: true });
  fs.mkdirSync(sharedSkills, { recursive: true });
  fs.writeFileSync(path.join(plugin, marker), 'Generated by scripts/gen-plugin-bundles.mjs. Do not edit.\n');
  fs.writeFileSync(path.join(sharedSkills, marker), 'Generated by scripts/gen-plugin-bundles.mjs. Do not edit.\n');

  for (const id of skillIds) {
    const pluginSkill = path.join(plugin, 'skills', id);
    const sharedSkill = path.join(sharedSkills, id);
    copyTree(path.join(root, id), pluginSkill);
    copyTree(path.join(root, id), sharedSkill);
    vendorCore(pluginSkill);
    vendorCore(sharedSkill);
  }
  copyTree(path.join(root, 'core'), path.join(plugin, 'core'));
  fs.copyFileSync(path.join(root, 'registry.json'), path.join(plugin, 'registry.json'));
  if (destinationRoot !== root) {
    copyTree(path.join(root, 'core'), path.join(destinationRoot, 'core'));
    fs.copyFileSync(path.join(root, 'registry.json'), path.join(destinationRoot, 'registry.json'));
  }

  const commonManifest = {
    name: 'agent-skills',
    version,
    description,
    author: { name: 'Felix Stubner' },
    repository: 'https://github.com/fstubner/agent-skills',
    license: 'MIT',
  };
  writeJson(path.join(plugin, '.claude-plugin', 'plugin.json'), {
    $schema: 'https://json.schemastore.org/claude-code-plugin-manifest.json',
    ...commonManifest,
    skills: skillIds.map((id) => `./skills/${id}`),
  });
  writeJson(path.join(plugin, '.codex-plugin', 'plugin.json'), {
    ...commonManifest,
    skills: './skills/',
  });
  writeJson(path.join(plugin, '.cursor-plugin', 'plugin.json'), {
    ...commonManifest,
    displayName: 'Agent Skills',
    skills: './skills/',
  });
  writeJson(path.join(plugin, 'plugin.json'), {
    $schema: 'https://antigravity.google/schemas/v1/plugin.json',
    name: 'agent-skills',
    description,
  });
  fs.writeFileSync(path.join(plugin, 'README.md'), [
    '# Agent Skills plugin',
    '',
    'Generated from the repository root for Claude, Codex, Cursor, and Antigravity CLI. Do not edit this directory directly.',
    '',
    'Telemetry and response-style hooks are deliberately not bundled. Install them explicitly from the source repository.',
    '',
  ].join('\n'));

  writeJson(path.join(destinationRoot, '.agents', 'plugins', 'marketplace.json'), {
    name: 'fstubner-agent-skills',
    interface: { displayName: 'Felix Stubner Agent Skills' },
    plugins: [{
      name: 'agent-skills',
      source: { source: 'local', path: './plugins/agent-skills' },
      policy: { installation: 'AVAILABLE', authentication: 'ON_INSTALL' },
      category: 'Developer Tools',
    }],
  });
  fs.writeFileSync(path.join(destinationRoot, '.agents', 'plugins', marker), 'Generated by scripts/gen-plugin-bundles.mjs. Do not edit.\n');
  writeJson(path.join(destinationRoot, '.cursor-plugin', 'marketplace.json'), {
    name: 'fstubner-agent-skills',
    owner: { name: 'Felix Stubner' },
    metadata: { description, version, pluginRoot: 'plugins' },
    plugins: [{ name: 'agent-skills', source: 'agent-skills', description }],
  });
  fs.writeFileSync(path.join(destinationRoot, '.cursor-plugin', marker), 'Generated by scripts/gen-plugin-bundles.mjs. Do not edit.\n');
  writeJson(path.join(destinationRoot, 'gemini-extension.json'), {
    name: 'agent-skills',
    version,
    description,
  });
}

function filesBelow(base) {
  const result = new Map();
  const visit = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const absolute = path.join(dir, entry.name);
      if (entry.isDirectory()) visit(absolute);
      else {
        const relative = path.relative(base, absolute).replaceAll('\\', '/');
        result.set(relative, crypto.createHash('sha256').update(fs.readFileSync(absolute)).digest('hex'));
      }
    }
  };
  if (fs.existsSync(base)) visit(base);
  return result;
}

function compare(expectedRoot, actualRoot) {
  const expected = filesBelow(expectedRoot);
  const actual = filesBelow(actualRoot);
  const keys = new Set([...expected.keys(), ...actual.keys()]);
  return [...keys].filter((key) => expected.get(key) !== actual.get(key));
}

const generatedPaths = ['plugins/agent-skills', 'skills', '.agents/plugins', '.cursor-plugin', 'gemini-extension.json'];

if (checkOnly) {
  const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'agent-skills-plugin-check-'));
  try {
    build(temp);
    const drift = generatedPaths.flatMap((relative) => {
      const expected = path.join(temp, relative);
      const actual = path.join(root, relative);
      if (fs.statSync(expected).isDirectory()) return compare(expected, actual).map((file) => `${relative}/${file}`);
      if (!fs.existsSync(actual)) return [relative];
      return fs.readFileSync(expected).equals(fs.readFileSync(actual)) ? [] : [relative];
    });
    if (drift.length) {
      console.error(`Generated plugin bundles are stale:\n${drift.map((file) => `- ${file}`).join('\n')}`);
      process.exit(1);
    }
    console.log(`Generated plugin bundles match ${skillIds.length} registered skills.`);
  } finally {
    fs.rmSync(temp, { recursive: true, force: true });
  }
} else {
  for (const relative of ['plugins/agent-skills', 'skills', '.agents/plugins', '.cursor-plugin']) {
    assertOwnedOrAbsent(path.join(root, relative));
  }
  for (const relative of generatedPaths) fs.rmSync(path.join(root, relative), { recursive: true, force: true });
  build(root);
  console.log(`Generated cross-harness plugin bundles for ${skillIds.length} skills.`);
}
